"""Hosted embedding provider.

Embeddings are always generated by a hosted model through an OpenAI-compatible
endpoint (Google Gemini's OpenAI-compatible API, OpenAI, or a custom gateway).
No local models, no synonym tables, no feature-hash fallback — if credentials
are missing we fail fast rather than silently degrade to retrieval that cannot
capture semantic similarity.
"""
from __future__ import annotations

import math
from typing import Protocol, runtime_checkable

from ..config import settings


@runtime_checkable
class Embedder(Protocol):
    def embed_texts(self, texts: list[str]) -> list[list[float]]: ...

    def dim(self) -> int: ...


class OpenAIEmbedder:
    """Hosted embeddings via an OpenAI-compatible endpoint (Gemini or OpenAI)."""

    def __init__(
        self,
        api_key: str | None = None,
        base_url: str | None = None,
        model: str | None = None,
    ) -> None:
        self.api_key = api_key or settings.embedding_api_key_resolved
        self.base_url = base_url or settings.embedding_base_url_resolved
        self.model = model or settings.embedding_model_resolved
        if not self.api_key:
            raise RuntimeError(
                "Missing embeddings credentials: set LLM_API_KEY (Gemini) or "
                "EMBEDDING_API_KEY/OPENAI_API_KEY."
            )
        # Lazy import keeps boot fast and avoids requiring the SDK when unused.
        from openai import OpenAI

        self._client = OpenAI(api_key=self.api_key, base_url=self.base_url)

    @property
    def index_identity(self) -> str:
        # Credentials deliberately excluded: rotating a key does not change vectors.
        return f"{self.base_url.rstrip('/')}|{self.model}"

    def dim(self) -> int:
        return len(self.embed_texts(["dimension probe"])[0])

    def embed_texts(self, texts: list[str]) -> list[list[float]]:
        vectors = []
        for start in range(0, len(texts), 64):
            batch = texts[start:start + 64]
            resp = self._client.embeddings.create(
                model=self.model, input=batch, encoding_format="float", timeout=30)
            # Some compatible endpoints omit the zero-valued index. Recover
            # only one uniquely missing index; reject ambiguous response order.
            indexed = [(item.index, item) for item in resp.data]
            missing = set(range(len(batch))) - {i for i, _ in indexed if i is not None}
            if sum(i is None for i, _ in indexed) == 1 and len(missing) == 1:
                inferred = next(iter(missing))
                indexed = [(inferred if i is None else i, item) for i, item in indexed]
            if any(i is None for i, _ in indexed):
                raise RuntimeError("Embedding provider returned ambiguous vector order")
            indexed.sort(key=lambda pair: pair[0])
            ordered = [item for _, item in indexed]
            if [i for i, _ in indexed] != list(range(len(batch))):
                raise RuntimeError("Embedding provider returned missing or duplicate vectors")
            for item in ordered:
                vector = item.embedding
                if not vector or not all(math.isfinite(x) for x in vector) or not any(vector):
                    raise RuntimeError("Embedding provider returned invalid vectors")
                if vectors and len(vector) != len(vectors[0]):
                    raise RuntimeError("Embedding provider returned inconsistent dimensions")
                vectors.append(vector)
        return vectors


def get_embedder() -> Embedder:
    """Always hosted. Fails fast when no embedding credentials are configured."""
    import logging

    if not settings.embedding_api_key_resolved:
        raise RuntimeError(
            "No embedding credentials configured. Set LLM_API_KEY (Gemini) or "
            "EMBEDDING_API_KEY/OPENAI_API_KEY."
        )
    logging.getLogger("omnicare.rag").info(
        "using hosted embeddings: %s / %s",
        settings.embedding_provider_resolved,
        settings.embedding_model_resolved,
    )
    return OpenAIEmbedder()
